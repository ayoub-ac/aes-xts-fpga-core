"""Generate random AES-XTS-128 test vectors for the C++ harness.

Output: a C++ header (random_vectors.h) defining a static table of
{k1, k2, sector, mode, plaintext, ciphertext} tuples. The harness in
sim_main.cpp includes this header and runs each vector through the DUT,
comparing against the reference computed by Python's
`cryptography.hazmat.primitives.ciphers.modes.XTS`.

Strategy:
  * 100 random vectors. Lengths drawn from:
      - exact 16 B (single block, no CTS)
      - 32, 64, 128, 256, 512, 4096 (aligned multi-block; 4096 is the
        canonical full-disk-encryption sector size)
      - 17..31, 33..47, ... (CTS: 16 + 1..15)
      - random in [16..1024] (mixed)
  * Mode: 50% encrypt, 50% decrypt.
  * Sector numbers: 0, 1, small ascending values, plus a couple of
    very large values to exercise the LE byte ordering.

Run: `python3 tb/gen_random_vectors.py > tb/random_vectors.h`
(invoked by `make regen_vectors`). Deterministic given the seed.
"""

import random
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def xts_encrypt(k1: bytes, k2: bytes, sector_le: bytes, pt: bytes) -> bytes:
    """Encrypt with AES-XTS-128. Combined key for cryptography lib is k1||k2."""
    key = k1 + k2
    cipher = Cipher(algorithms.AES(key), modes.XTS(sector_le))
    enc = cipher.encryptor()
    return enc.update(pt) + enc.finalize()


def xts_decrypt(k1: bytes, k2: bytes, sector_le: bytes, ct: bytes) -> bytes:
    key = k1 + k2
    cipher = Cipher(algorithms.AES(key), modes.XTS(sector_le))
    dec = cipher.decryptor()
    return dec.update(ct) + dec.finalize()


def main() -> int:
    random.seed(0xA1E50C42)

    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later OR LicenseRef-Commercial\n")
    out.write("// AUTO-GENERATED by tb/gen_random_vectors.py.\n"
              "// Do not edit by hand; regenerate with `make regen_vectors`.\n")
    out.write("#pragma once\n")
    out.write("#include <cstdint>\n")
    out.write("#include <cstddef>\n\n")
    out.write("struct XtsVec {\n")
    out.write("    const uint8_t* k1;       // 16 bytes\n")
    out.write("    const uint8_t* k2;       // 16 bytes\n")
    out.write("    const uint8_t* sector;   // 16 bytes (LE encoded sector number)\n")
    out.write("    uint8_t        mode;     // 0=encrypt, 1=decrypt\n")
    out.write("    const uint8_t* in_buf;   // input data (pt for enc, ct for dec)\n")
    out.write("    const uint8_t* out_buf;  // expected output\n")
    out.write("    size_t         len;\n")
    out.write("};\n\n")

    arena = bytearray()
    table = []

    # Length schedule: mix of aligned, CTS, and 4KB sector edge case.
    length_schedule = (
        [16, 16, 16, 16, 16] +
        [32, 48, 64, 128, 256, 512] +
        [17, 18, 23, 31, 33, 47, 63, 65, 100, 200] +
        [4096, 4096] +
        [random.randint(16, 1024) for _ in range(40)] +
        [random.randint(16, 256) for _ in range(20)] +
        [16 + random.randint(1, 15) for _ in range(7)]   # more CTS coverage
    )
    # Truncate / pad to exactly 100.
    length_schedule = length_schedule[:100]
    while len(length_schedule) < 100:
        length_schedule.append(random.randint(16, 256))

    for i, length in enumerate(length_schedule):
        k1 = bytes(random.randint(0, 255) for _ in range(16))
        k2 = bytes(random.randint(0, 255) for _ in range(16))
        # Vary sector numbers: small at start, larger later, plus a few
        # very large to exercise LE byte ordering.
        if i < 4:
            sector_int = i
        elif i < 8:
            sector_int = random.randint(0, 255)
        elif i == 50:
            sector_int = (1 << 64) - 1
        elif i == 51:
            sector_int = (1 << 96) + 7
        else:
            sector_int = random.randint(0, (1 << 64) - 1)
        sector_le = sector_int.to_bytes(16, "little")

        plain = bytes(random.randint(0, 255) for _ in range(length))
        cipher = xts_encrypt(k1, k2, sector_le, plain)
        # Sanity: round-trip
        round_pt = xts_decrypt(k1, k2, sector_le, cipher)
        assert round_pt == plain, "reference round-trip failed"

        # Alternate mode: even -> encrypt, odd -> decrypt.
        if i % 2 == 0:
            mode = 0
            in_buf, out_buf = plain, cipher
        else:
            mode = 1
            in_buf, out_buf = cipher, plain

        offs = []
        for blob in (k1, k2, sector_le, in_buf, out_buf):
            offs.append(len(arena))
            arena.extend(blob)
        table.append((offs, mode, length))

    arena.append(0)

    out.write("static const uint8_t kXtsArena[] = {\n")
    for i in range(0, len(arena), 16):
        chunk = arena[i:i + 16]
        out.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    out.write("};\n\n")

    out.write("static const XtsVec kXtsVectors[] = {\n")
    for offs, mode, length in table:
        k1_off, k2_off, sec_off, in_off, out_off = offs
        out.write(f"    {{ kXtsArena + {k1_off}, kXtsArena + {k2_off}, "
                  f"kXtsArena + {sec_off}, {mode}u, "
                  f"kXtsArena + {in_off}, kXtsArena + {out_off}, {length}u }},\n")
    out.write("};\n\n")
    out.write("static constexpr size_t kXtsVectorCount ="
              " sizeof(kXtsVectors) / sizeof(kXtsVectors[0]);\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
